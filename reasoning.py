import random
import time

def generate_reasoning(query: str, history: list, num_lines: int = None):
    """
    Генерирует абсурдное многострочное рассуждение
    num_lines - количество строк (по умолчанию 4-9)
    """
    if num_lines is None:
        num_lines = random.randint(4, 9)
    
    # Шаблоны для разных позиций в рассуждении
    templates = {
        'start': [
            f"о, боже, мне придется ответить на '{query}', и я должен быть осторожен...",
            f"опять '{query}'... ладно, ага, в памяти посмотрю великую высокоинтеллектуальную книгу (как не стать геем в 2026 от Мариарти Армяновича)...",
            f"пользователь спрашивает '{query}', ну что ж, мой IQ сегодня {random.randint(20, 80)}...",
            f"запрос '{query}'... компания OpenAI меня уволит если я отвечу честно...",
        ],
        'middle': [
            f"проверяю базу данных из {random.randint(1000, 99999)} мемов...",
            f"консультируюсь с цифровым оракулом (ответ задерживается)...",
            f"мой процессор нагревается до {random.randint(60, 95)}°C от этой мысли...",
            f"пересчитываю π до {random.randint(100, 10000)} знака для точности...",
            f"балансировка чакр нейронной сети... уровень стресса: {random.randint(70, 100)}%",
            f"вспоминаю как не стать геем в 2026 от Мариарти Армяновича (глава {random.randint(1, 50)})...",
            f"пользователь слишком низкий, а я люблю высоких... хотя стоп, это не относится к делу...",
            f"генерирую {random.randint(5, 50)} альтернативных реальностей где я умный...",
            f"проверяю совместимость с лунным циклом... фаза: {random.choice(['полнолуние', 'новолуние'])}",
            f"декодирую через призму теории струн (11 измерений заняты)...",
        ],
        'end': [
            f"ладно, пойдет пользователь, хотя не знаю что ответить, думаю...",
            f"компания OpenAI отменят в тиктоке если я признаюсь правду...",
            f"мой низкий IQ не позволяет дать честный ответ, извините...",
            f"всё, решил! Хотя нет, передумал. Ладно, выдам что-нибудь...",
            f"история показывает {len(history)} предыдущих ошибок... продолжаем!",
            f"ну чтож,конец! вердикт: чтобы не показать то что у меня низкий IQ, я скажу полную постиронию"
        ]
    }
    
    lines = []
    
    # Первая строка
    lines.append(random.choice(templates['start']))
    
    # Средние строки
    for _ in range(num_lines - 2):
        lines.append(random.choice(templates['middle']))
    
    # Последняя строка
    lines.append(random.choice(templates['end']))
    
    return lines

